const dicts = { id, en };

function loadLang() {
  try {
    const value = localStorage.getItem(LS_LANG);
    return value === 'en' || value === 'id' ? value : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

let lang = loadLang();

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = dicts[next] ? next : DEFAULT_LANG;
  try {
    localStorage.setItem(LS_LANG, lang);
  } catch {
    /* storage unavailable — language just won't persist */
  }
}

export function t(key, params = {}) {
  const dict = dicts[lang] || dicts[DEFAULT_LANG];
  let text = dict[key] ?? dicts[DEFAULT_LANG][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) =>
    params[name] !== undefined ? String(params[name]) : `{${name}}`
  );
}

// BCP-47 tag for locale-aware date/number formatting in the UI.
export function dateLocale() {
  return lang === 'id' ? 'id-ID' : 'en-US';
}
